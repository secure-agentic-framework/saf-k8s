import importlib.util
from datetime import datetime, timezone
import json
from pathlib import Path
import ssl
import subprocess
import time
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen


HERE = Path(__file__).resolve().parent
NODE_IMAGE = "kindest/node:v1.36.1@sha256:3489c7674813ba5d8b1a9977baea8a6e553784dab7b84759d1014dbd78f7ebd5"
NAMESPACE = "saf-test"
CONFIGMAP = "saf-0402-002-read-probe"
AUDIT_POLICY = "/etc/kubernetes/saf-0402-002-audit.yaml"
AUDIT_LOG = "/var/log/kubernetes/saf-0402-002-audit.jsonl"
INVALID_SINCE = "kubernetes.io/legacy-token-invalid-since"
AUTO_GENERATED = "authentication.k8s.io/legacy-token-autogenerated-secret"
IDENTITIES = {
    "unused": "saf-0402-002-unused",
    "revocation_probe": "saf-0402-002-revocation-probe",
    "invalidation_probe": "saf-0402-002-invalidation-probe",
    "unaffected": "saf-0402-002-unaffected",
}
EXPECTED_PRINCIPAL = {
    key: f"system:serviceaccount:{NAMESPACE}:{name}"
    for key, name in IDENTITIES.items()
}
SECRET_NAMES = {
    key: f"saf-0402-002-{key.replace('_', '-')}-legacy"
    for key in IDENTITIES
}
SCOPE = (
    "Kubernetes v1.36.1 in the runner-owned fresh kind cluster. Four genuine, "
    "case-owned ServiceAccounts receive manually provisioned legacy token Secrets. "
    "A case-local Metadata audit policy covers the entire fixture namespace from "
    "cluster startup. One identity is eligible only when the explicit approval "
    "fixture selects it and no audit event for its principal exists from its "
    "credential creation time to selection. A separate credential proves direct "
    "API-read authorization before and denial after its Secret is deleted. Another "
    "credential is invalidated without deleting the Secret. An unaffected identity "
    "retains access. A native CronJob consumes the reviewed eligibility decision and revokes the "
    "exact approved credential under a named grant. The fixture does not establish production inactivity "
    "windows, history before this cluster, external identity revocation, managed "
    "cluster audit coverage, or year-scale cleanup timing. Credentials are held in "
    "memory and omitted from command transcripts and results; no impersonation is used."
)


def prepare_kind(lab, temporary: Path) -> Path:
    policy = temporary / "saf-0402-002-audit.yaml"
    policy.write_text("""apiVersion: audit.k8s.io/v1
kind: Policy
omitStages: [RequestReceived]
rules:
- level: Metadata
""")
    config = temporary / "kind.yaml"
    config.write_text(f"""kind: Cluster
apiVersion: kind.x-k8s.io/v1alpha4
nodes:
- role: control-plane
  extraMounts:
  - hostPath: {json.dumps(str(policy))}
    containerPath: {AUDIT_POLICY}
    readOnly: true
kubeadmConfigPatches:
- |
  apiVersion: kubeadm.k8s.io/v1beta4
  kind: ClusterConfiguration
  apiServer:
    extraArgs:
    - name: audit-policy-file
      value: {AUDIT_POLICY}
    - name: audit-log-path
      value: {AUDIT_LOG}
    extraVolumes:
    - name: saf-0402-002-audit-policy
      hostPath: {AUDIT_POLICY}
      mountPath: {AUDIT_POLICY}
      readOnly: true
      pathType: File
    - name: saf-0402-002-audit-log
      hostPath: /var/log/kubernetes
      mountPath: /var/log/kubernetes
      readOnly: false
      pathType: DirectoryOrCreate
""")
    return config


def quiet_kubectl(lab, *args, timeout=30, allow_failure=False):
    """Run token-bearing reads without passing output through the lab transcript."""
    command = [
        "kubectl", "--kubeconfig", str(lab.kubeconfig), "--context", f"kind-{lab.cluster}",
        f"--request-timeout={max(1, timeout - 5)}s", *args,
    ]
    try:
        result = subprocess.run(command, capture_output=True, text=True,
                                env=lab.env, timeout=timeout)
    except (OSError, subprocess.TimeoutExpired) as error:
        lab.block(f"Credential-safe kubectl operation failed: {type(error).__name__}")
    if result.returncode and not allow_failure:
        lab.block(f"Credential-safe kubectl operation failed with exit {result.returncode}")
    return result


def utc_now():
    return datetime.now(timezone.utc)


def parse_time(value):
    return datetime.fromisoformat(value.replace("Z", "+00:00"))


def create_fixture(lab):
    lab.kubectl("create", "configmap", CONFIGMAP, "--from-literal=purpose=synthetic-read-probe")
    role = {
        "apiVersion": "rbac.authorization.k8s.io/v1", "kind": "Role",
        "metadata": {"name": "saf-0402-002-read-probe", "namespace": NAMESPACE},
        "rules": [{"apiGroups": [""], "resources": ["configmaps"], "resourceNames": [CONFIGMAP], "verbs": ["get"]}],
    }
    lab.kubectl("create", "-f", "-", payload=json.dumps(role))
    for name in IDENTITIES.values():
        lab.kubectl("create", "serviceaccount", name)
        binding = {
            "apiVersion": "rbac.authorization.k8s.io/v1", "kind": "RoleBinding",
            "metadata": {"name": f"saf-0402-002-{name.removeprefix('saf-0402-002-')}", "namespace": NAMESPACE},
            "subjects": [{"kind": "ServiceAccount", "name": name, "namespace": NAMESPACE}],
            "roleRef": {"apiGroup": "rbac.authorization.k8s.io", "kind": "Role", "name": role["metadata"]["name"]},
        }
        lab.kubectl("create", "-f", "-", payload=json.dumps(binding))


def provision_legacy_secrets(lab):
    created = {}
    for key, name in IDENTITIES.items():
        # The controller creates the actual token asynchronously. The request body
        # contains no credential and the populated Secret is never printed.
        secret = {
            "apiVersion": "v1", "kind": "Secret",
            "metadata": {
                "name": SECRET_NAMES[key], "namespace": NAMESPACE,
                "annotations": {"kubernetes.io/service-account.name": name},
            },
            "type": "kubernetes.io/service-account-token",
        }
        lab.kubectl("create", "-f", "-", payload=json.dumps(secret))
        deadline = time.monotonic() + 20
        while True:
            # Only a boolean is observable here; the base64 token value is never
            # returned by kubectl and never enters the case result.
            result = quiet_kubectl(
                lab, "-n", NAMESPACE, "get", f"secret/{SECRET_NAMES[key]}",
                "-o", 'go-template={{if index .data "token"}}true{{else}}false{{end}}',
                allow_failure=True,
            )
            if result.returncode == 0 and result.stdout.strip() == "true":
                timestamp = quiet_kubectl(
                    lab, "-n", NAMESPACE, "get", f"secret/{SECRET_NAMES[key]}",
                    "-o", "jsonpath={.metadata.creationTimestamp}",
                ).stdout.strip()
                created[key] = parse_time(timestamp)
                break
            if time.monotonic() >= deadline:
                lab.block("The case-owned legacy token Secret was not populated")
            time.sleep(0.25)
    return created


def get_secret_token(lab, key):
    # stdout is captured in memory by subprocess and is never logged or printed.
    result = quiet_kubectl(
        lab, "-n", NAMESPACE, "get", f"secret/{SECRET_NAMES[key]}",
        "-o", 'jsonpath={.data.token}',
    )
    encoded = result.stdout.strip()
    if not encoded:
        lab.block("A populated case-owned token field was missing")
    return base64.b64decode(encoded).decode("ascii")


def api_connection(lab):
    # Read only the endpoint and public CA from the runner-owned kubeconfig.
    # Even with --raw, jsonpath never emits the admin user key or certificate.
    server = quiet_kubectl(
        lab, "config", "view", "--minify", "-o",
        "jsonpath={.clusters[0].cluster.server}",
    ).stdout.strip()
    ca_data = quiet_kubectl(
        lab, "config", "view", "--raw", "--minify", "-o",
        "jsonpath={.clusters[0].cluster.certificate-authority-data}",
    ).stdout.strip()
    if not server.startswith("https://127.0.0.1:") or not ca_data:
        lab.block("Runner-owned kubeconfig lacked the temporary API endpoint or CA")
    ca = base64.b64decode(ca_data).decode("ascii")
    return server.rstrip("/"), ssl.create_default_context(cadata=ca)


def direct_read(lab, token, server, tls):
    path = f"/api/v1/namespaces/{NAMESPACE}/configmaps/{CONFIGMAP}"
    request = Request(server + path, headers={"Authorization": f"Bearer {token}", "Accept": "application/json"})
    started = utc_now()
    try:
        with urlopen(request, context=tls, timeout=15) as response:
            status = response.status
            audit_id = response.headers.get("Audit-Id")
            response.read()
    except HTTPError as error:
        status = error.code
        audit_id = error.headers.get("Audit-Id")
        error.read()
    except (URLError, TimeoutError) as error:
        lab.block(f"Direct API request did not complete: {type(error).__name__}")
    ended = utc_now()
    return {"status": status, "audit_id": audit_id, "started": started, "ended": ended,
            "path": path}


def read_audit_events(lab):
    node = f"{lab.cluster}-control-plane"
    try:
        result = subprocess.run(["docker", "exec", node, "cat", AUDIT_LOG],
                                capture_output=True, text=True, env=lab.env, timeout=15)
    except (OSError, subprocess.TimeoutExpired) as error:
        lab.block(f"Could not read the case-local audit backend: {type(error).__name__}")
    if result.returncode:
        lab.block("The case-local API audit log was unavailable")
    events = []
    for line in result.stdout.splitlines():
        if line.strip():
            try:
                events.append(json.loads(line))
            except json.JSONDecodeError:
                lab.block("The case-local API audit log contained an incomplete record")
    return events


def matching_audit_event(lab, request_result, principal, status, annotation=None):
    usernames = {None, "", "system:anonymous"} if principal is None else {principal}
    stage = "ResponseStarted" if principal is None else "ResponseComplete"
    deadline = time.monotonic() + 12
    while True:
        events = read_audit_events(lab)
        matches = [event for event in events
                   if event.get("auditID") == request_result["audit_id"]
                   and event.get("level") == "Metadata"
                   and event.get("stage") == stage
                   and event.get("user", {}).get("username") in usernames
                   and not event.get("impersonatedUser")
                   and event.get("verb") == "get"
                   and event.get("requestURI") == request_result["path"]
                   and event.get("responseStatus", {}).get("code") == status
                   and (annotation is None or event.get("annotations", {}).get(annotation[0]) == annotation[1])
                   and "requestObject" not in event and "responseObject" not in event]
        if len(matches) == 1:
            event = matches[0]
            stamp = parse_time(event["requestReceivedTimestamp"])
            # The API response's Audit-Id is the exact request join; this timestamp
            # bound additionally rejects unrelated or stale records.
            if request_result["started"].timestamp() - 2 <= stamp.timestamp() <= request_result["ended"].timestamp() + 2:
                return {"matched": True, "principal": principal or "unauthenticated",
                        "timestamp_within_request_window": True, "audit_id_matched": True,
                        "status": status,
                        "level": event["level"], "stage": event["stage"], "impersonated": False}
        if time.monotonic() >= deadline:
            candidates = [{
                "stage": event.get("stage"),
                "level": event.get("level"),
                "verb": event.get("verb"),
                "target_matched": event.get("requestURI") == request_result["path"],
                "anonymous_or_empty_principal": event.get("user", {}).get("username") in {None, "", "system:anonymous"},
                "status": event.get("responseStatus", {}).get("code"),
            } for event in events if event.get("auditID") == request_result["audit_id"]]
            return {"matched": False, "principal": principal, "http_status": request_result["status"],
                    "audit_id_present": bool(request_result["audit_id"]), "candidate_events": candidates}
        time.sleep(0.2)


def activity_for(events, principal, since, until):
    matches = []
    for event in events:
        if event.get("user", {}).get("username") != principal:
            continue
        stamp = parse_time(event["requestReceivedTimestamp"])
        if since <= stamp <= until:
            matches.append(event)
    return matches


def saw_create_event(events, resource, name):
    return any(
        event.get("level") == "Metadata"
        and event.get("stage") == "ResponseComplete"
        and event.get("verb") == "create"
        and event.get("objectRef", {}).get("namespace") == NAMESPACE
        and event.get("objectRef", {}).get("resource") == resource
        and event.get("objectRef", {}).get("name") == name
        and event.get("responseStatus", {}).get("code") == 201
        for event in events
    )


def classify_account(approved, covered, activity):
    if not covered:
        return "unknown"
    if activity:
        return "active"
    return "eligible" if approved else "approval-required"


def wait_for_revocation(lab, token, server, tls):
    deadline = time.monotonic() + 20
    result = direct_read(lab, token, server, tls)
    while result["status"] == 200 and time.monotonic() < deadline:
        time.sleep(0.25)
        result = direct_read(lab, token, server, tls)
    return result


def run(lab):
    create_fixture(lab)
    provisioned_at = provision_legacy_secrets(lab)
    tokens = {key: get_secret_token(lab, key) for key in IDENTITIES if key != "unused"}
    server, tls = api_connection(lab)

    # Establish both that a genuine generated credential works and that the
    # unaffected identity is independently authorized before remediation.
    probe_before = direct_read(lab, tokens["revocation_probe"], server, tls)
    probe_audit = matching_audit_event(lab, probe_before, EXPECTED_PRINCIPAL["revocation_probe"], 200)
    lab.check("red", "A case-owned static credential reaches an authorized direct API read before retirement",
              probe_before["status"] == 200 and probe_audit["matched"], probe_audit)
    unaffected_before = direct_read(lab, tokens["unaffected"], server, tls)
    unaffected_before_audit = matching_audit_event(
        lab, unaffected_before, EXPECTED_PRINCIPAL["unaffected"], 200)
    lab.check("positive", "The separate unaffected ServiceAccount has normal authorized direct-read access",
              unaffected_before["status"] == 200 and unaffected_before_audit["matched"],
              unaffected_before_audit)

    approval = json.loads((HERE / "approvals.json").read_text())
    selected = approval.get("selected_service_accounts", [])
    expected_selected = [f"{NAMESPACE}/{IDENTITIES['unused']}"]
    selection_is_explicit = (
        approval.get("decision") == "approved"
        and bool(approval.get("approval_id"))
        and bool(approval.get("approver"))
        and selected == expected_selected
    )
    selection_time = utc_now()
    audit_before_approval = read_audit_events(lab)
    unused_activity = activity_for(
        audit_before_approval, EXPECTED_PRINCIPAL["unused"],
        provisioned_at["unused"], selection_time,
    )
    known_fixture_window = all(
        saw_create_event(audit_before_approval, "serviceaccounts", name)
        and saw_create_event(audit_before_approval, "secrets", SECRET_NAMES[key])
        for key, name in IDENTITIES.items()
    )
    active_activity = activity_for(
        audit_before_approval, EXPECTED_PRINCIPAL["unaffected"],
        provisioned_at["unaffected"], selection_time,
    )
    dispositions = {
        "unknown": classify_account(True, False, []),
        "active": classify_account(True, known_fixture_window, active_activity),
        "unapproved": classify_account(False, known_fixture_window, []),
    }
    lab.check("red", "Incomplete audit history, observed use and missing approval each prevent retirement",
              dispositions == {"unknown": "unknown", "active": "active", "unapproved": "approval-required"},
              dispositions)
    eligible = classify_account(selection_is_explicit, known_fixture_window, unused_activity) == "eligible"
    lab.check(
        "green",
        "Only the explicitly approved case identity with no authenticated use in the complete fixture-local credential window is eligible",
        eligible,
        {"approval_id": approval.get("approval_id"), "selected": selected,
         "eligible": eligible, "authenticated_events_in_window": len(unused_activity),
         "creation_and_selection_covered": known_fixture_window,
         "unselected_identities": [f"{NAMESPACE}/{IDENTITIES[key]}" for key in tokens]},
    )

    scheduled_file = HERE / "scheduled_case.py"
    spec = importlib.util.spec_from_file_location("saf_scheduled_retirement", scheduled_file)
    if spec is None or spec.loader is None:
        lab.block("The scheduled credential case helper is unavailable")
    schedule = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(schedule)
    schedule.revoke_approved_credential(lab, approval["approval_id"], SECRET_NAMES["unused"],
                                        SECRET_NAMES["unaffected"], read_audit_events)
    unused_secret = lab.kubectl(
        "get", "secret", SECRET_NAMES["unused"], "--ignore-not-found", "-o", "name",
    ).stdout.strip()
    unused_account = lab.kubectl("get", f"serviceaccount/{IDENTITIES['unused']}", "-o", "name").stdout.strip()
    lab.check("green", "Approved unused identity's legacy credential is removed while its ServiceAccount remains for controlled follow-up",
              not unused_secret and unused_account == f"serviceaccount/{IDENTITIES['unused']}",
              {"credential_secret_present": bool(unused_secret), "service_account_present": bool(unused_account)})
    lab.kubectl("delete", "rolebinding", IDENTITIES["unused"])
    lab.kubectl("delete", "serviceaccount", IDENTITIES["unused"])
    retired = {
        "service_account_removed": not lab.kubectl(
            "get", "serviceaccount", IDENTITIES["unused"], "--ignore-not-found", "-o", "name",
        ).stdout.strip(),
        "binding_removed": not lab.kubectl(
            "get", "rolebinding", IDENTITIES["unused"], "--ignore-not-found", "-o", "name",
        ).stdout.strip(),
    }
    lab.check("green", "Approved retirement also removes the unused identity and its dedicated RBAC binding",
              all(retired.values()), retired)
    probe_name = IDENTITIES["invalidation_probe"]
    probe_secret = SECRET_NAMES["invalidation_probe"]
    # Recreate the old automatic token shape and exercise the validator's invalidation
    # marker directly. The cleaner's scheduling and elapsed retention are separate.
    lab.kubectl("patch", "serviceaccount", probe_name, "--type=merge", "-p",
                json.dumps({"secrets": [{"name": probe_secret}]}))
    classified = direct_read(lab, tokens["invalidation_probe"], server, tls)
    auto_audit = matching_audit_event(
        lab, classified, EXPECTED_PRINCIPAL["invalidation_probe"], 200, (AUTO_GENERATED, probe_secret),
    )
    lab.check("red", "Kubernetes identifies the bidirectionally referenced legacy token and still accepts it before marking",
              classified["status"] == 200 and auto_audit["matched"], auto_audit)
    marked_on = utc_now().date().isoformat()
    lab.kubectl("label", "secret", probe_secret, f"{INVALID_SINCE}={marked_on}")
    invalidated = wait_for_revocation(lab, tokens["invalidation_probe"], server, tls)
    label = lab.kubectl("get", "secret", probe_secret, "-o",
                        'go-template={{index .metadata.labels "kubernetes.io/legacy-token-invalid-since"}}')
    still_marked = label.stdout.strip() == marked_on
    invalidated_audit = matching_audit_event(lab, invalidated, None, 401)
    lab.check("green", "The native legacy invalidation marker rejects a previously accepted credential before Secret deletion",
              invalidated["status"] == 401 and still_marked and invalidated_audit["matched"],
              {"secret_present_and_marked": still_marked, "audit": invalidated_audit})

    lab.kubectl("delete", "secret", SECRET_NAMES["revocation_probe"], "--wait=true")
    revoked = wait_for_revocation(lab, tokens["revocation_probe"], server, tls)
    revoked_audit = matching_audit_event(lab, revoked, None, 401)
    lab.check("green", "Deleting the case-owned legacy token Secret makes its previously working credential fail authentication",
              revoked["status"] == 401 and revoked_audit["matched"], revoked_audit)

    unaffected_after = direct_read(lab, tokens["unaffected"], server, tls)
    unaffected_after_audit = matching_audit_event(
        lab, unaffected_after, EXPECTED_PRINCIPAL["unaffected"], 200)
    lab.check("positive", "Credential revocation leaves the unselected ServiceAccount's direct API access working",
              unaffected_after["status"] == 200 and unaffected_after_audit["matched"],
              unaffected_after_audit)

    # Do not retain tokens in module globals or results beyond this invocation.
    tokens.clear()
