"""Safely verify Cilium source-verification configuration and policy telemetry.

No crafted, spoofed, or injected packets are generated by this case.
"""
import hashlib
import json
from pathlib import Path
import time


NODE_IMAGE = (
    "kindest/node:v1.36.1@sha256:"
    "3489c7674813ba5d8b1a9977baea8a6e553784dab7b84759d1014dbd78f7ebd5"
)
KUBERNETES_VERSION = "v1.36.1"
KIND_VERSION = "v0.32.0"
CILIUM_VERSION = "1.20.5"
INSTALLS_CNI = True
CHART_SOURCE = "oci://quay.io/cilium/charts/cilium"
CHART_HASH = "0c7592eb75179ecf46dd3ec22145916f0164c4401214ea15afb5b230b1d11a21"
CILIUM_IMAGE = (
    "quay.io/cilium/cilium:v1.20.5@sha256:"
    "aa72499f075ad729947ea91b026218aceba24f1a8e4534bf36b8368c7c561526"
)
BUSYBOX_IMAGE = (
    "docker.io/library/busybox:1.37.0@sha256:"
    "a7dbc319b1438115a207e11930dc4bb3e643dcb3ec0bdd694bb36cd8fad289ec"
)
NAMESPACE = "saf-test"
CLIENT = "saf-0502-007-client"
DENIED_SINK = "saf-0502-007-denied-sink"
ALLOWED_SINK = "saf-0502-007-allowed-sink"
PORT = 18080
MARKERS = {
    DENIED_SINK: "saf-0502-007-denied-fixed-marker",
    ALLOWED_SINK: "saf-0502-007-allowed-fixed-marker",
}
ROLE = "saf-k8s.example/0502-007-role"
DISABLE_ANNOTATION = "config.cilium.io/disable-source-ip-verification"
DELEGATE_ANNOTATION = "config.cilium.io/delegate-source-ip-verification"
HUBBLE_SERVER = "unix:///var/run/cilium/hubble.sock"
SCOPE = (
    "One runner-owned Kind cluster running Kubernetes v1.36.1 with "
    "digest-pinned Cilium 1.20.5 and embedded Hubble. In the runner-created "
    "saf-test namespace, one non-root client Pod and two case-owned HTTP sink "
    "Pods exchange only fixed-marker IPv4 TCP/18080 requests. The case checks "
    "the active agent configuration, absence of namespace delegation and Pod "
    "opt-outs, and Hubble endpoint, IP, and policy verdicts for ordinary traffic. "
    "Direct invalid-source packet handling, additional CNIs, IPv6, host-network "
    "paths and production coverage remain unverified."
)


def prepare_kind(_lab, temporary):
    profile = temporary / "kind.yaml"
    profile.write_bytes(Path(__file__).with_name("kind-profile.yaml").read_bytes())
    return profile


def _kubectl(lab, *args, timeout=60, allow_failure=False, payload=None):
    return lab.command(
        "kubectl", "--kubeconfig", str(lab.kubeconfig), "--context", f"kind-{lab.cluster}",
        *args, payload=payload, timeout=timeout, allow_failure=allow_failure,
    )


def _create(lab, resource):
    return _kubectl(lab, "create", "-f", "-", payload=json.dumps(resource))


def _container(name, command):
    return {
        "name": name,
        "image": BUSYBOX_IMAGE,
        "command": command,
        "resources": {"requests": {"cpu": "5m", "memory": "8Mi"},
                      "limits": {"cpu": "75m", "memory": "24Mi"}},
        "securityContext": {
            "allowPrivilegeEscalation": False,
            "capabilities": {"drop": ["ALL"]},
            "runAsNonRoot": True,
            "runAsUser": 65534,
            "seccompProfile": {"type": "RuntimeDefault"},
        },
    }


def _pod(name, *, marker=None):
    if marker is None:
        command = ["sh", "-ec", "exec sleep 900"]
    else:
        command = ["sh", "-ec",
                   f"printf %s {marker} >/tmp/index.html; exec httpd -f -p {PORT} -h /tmp"]
    return {
        "apiVersion": "v1", "kind": "Pod",
        "metadata": {"name": name, "namespace": NAMESPACE,
                     "labels": {ROLE: name}},
        "spec": {"restartPolicy": "Never", "automountServiceAccountToken": False,
                 "terminationGracePeriodSeconds": 1,
                 "containers": [_container(name, command)]},
    }


def _wait_pod(lab, name):
    _kubectl(lab, "-n", NAMESPACE, "wait", "--for=condition=Ready", f"pod/{name}",
             "--timeout=90s", timeout=100)
    pod = json.loads(_kubectl(lab, "-n", NAMESPACE, "get", "pod", name, "-o", "json").stdout)
    ip = pod.get("status", {}).get("podIP")
    if pod.get("status", {}).get("phase") != "Running" or not ip:
        lab.block(f"Case-owned Pod {name} is not Running with a Pod IP")
    return ip


def _policy():
    return {
        "apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy",
        "metadata": {"name": "saf-0502-007-client-egress", "namespace": NAMESPACE},
        "spec": {
            "podSelector": {"matchLabels": {ROLE: CLIENT}},
            "policyTypes": ["Egress"],
            "egress": [{
                "to": [{"podSelector": {"matchLabels": {ROLE: ALLOWED_SINK}}}],
                "ports": [{"protocol": "TCP", "port": PORT}],
            }],
        },
    }


def _capture_policy(lab):
    live = json.loads(_kubectl(
        lab, "-n", NAMESPACE, "get", "networkpolicy", "saf-0502-007-client-egress", "-o", "json"
    ).stdout)
    expected = _policy()
    matches = (live.get("metadata", {}).get("name") == expected["metadata"]["name"]
               and live.get("metadata", {}).get("namespace") == NAMESPACE
               and live.get("spec") == expected["spec"])
    (lab.evidence / "networkpolicy-raw.json").write_text(json.dumps(live, indent=2) + "\n")
    normalized = {"name": live.get("metadata", {}).get("name"),
                  "namespace": live.get("metadata", {}).get("namespace"),
                  "spec": live.get("spec")}
    (lab.evidence / "networkpolicy-normalized.json").write_text(
        json.dumps(normalized, indent=2, sort_keys=True) + "\n")
    lab.check("green", "Live case-owned NetworkPolicy matches the exact CNI test allowlist",
              matches, {"policy_name": normalized["name"], "namespace": normalized["namespace"],
                        "selector_and_rules_match": matches})


def _cilium_exec(lab, *args, timeout=45):
    result = _kubectl(lab, "-n", "kube-system", "exec", "daemonset/cilium", "-c",
                      "cilium-agent", "--", *args, timeout=timeout)
    return result.stdout


def _install_cilium(lab):
    work = lab.kubeconfig.parent
    registry = work / "helm-registry.json"
    lab.command("helm", "pull", CHART_SOURCE, "--version", CILIUM_VERSION,
                "--destination", str(work), "--registry-config", str(registry), timeout=100)
    chart = work / f"cilium-{CILIUM_VERSION}.tgz"
    if hashlib.sha256(chart.read_bytes()).hexdigest() != CHART_HASH:
        lab.block("Downloaded Cilium chart does not match the reviewed content digest")
    lab.command(
        "helm", "install", "cilium", str(chart), "--namespace", "kube-system",
        "--kubeconfig", str(lab.kubeconfig), "--kube-context", f"kind-{lab.cluster}",
        "-f", str(Path(__file__).with_name("cilium-values.yaml")),
        "--wait", "--timeout", "4m", timeout=260,
    )
    _kubectl(lab, "-n", "kube-system", "rollout", "status", "daemonset/cilium",
             "--timeout=90s", timeout=100)
    _kubectl(lab, "wait", "--for=condition=Ready", "node", "--all", "--timeout=90s", timeout=105)
    daemonset = json.loads(_kubectl(lab, "-n", "kube-system", "get", "daemonset", "cilium",
                                    "-o", "json").stdout)
    containers = daemonset["spec"]["template"]["spec"]["containers"]
    image_ok = any(c.get("name") == "cilium-agent" and c.get("image") == CILIUM_IMAGE
                   for c in containers)
    status = daemonset.get("status", {})
    desired = status.get("desiredNumberScheduled", 0)
    ready = (desired > 0 and status.get("numberReady", 0) == desired
             and status.get("updatedNumberScheduled", 0) == desired
             and status.get("numberAvailable", 0) == desired)
    if not image_ok or not ready:
        lab.block("Pinned Cilium agent is not running on every Kind node")
    return {"image": CILIUM_IMAGE, "daemonset": {
        key: status.get(key, 0) for key in
        ("desiredNumberScheduled", "updatedNumberScheduled", "numberReady", "numberAvailable")
    }}


def _policy_configuration(lab):
    config = json.loads(_kubectl(lab, "-n", "kube-system", "get", "configmap", "cilium-config",
                                 "-o", "json").stdout)
    data = config.get("data", {})
    enabled = data.get("enable-source-ip-verification", "").lower() == "true"
    namespace = json.loads(_kubectl(lab, "get", "namespace", NAMESPACE, "-o", "json").stdout)
    namespace_annotations = namespace.get("metadata", {}).get("annotations", {})
    no_delegation = DELEGATE_ANNOTATION not in namespace_annotations
    evidence = {
        "cilium_configmap": config,
        "source_ip_verification_enabled": enabled,
        "namespace_annotations": namespace_annotations,
        "namespace_does_not_delegate_opt_out": no_delegation,
    }
    if not enabled or not no_delegation:
        lab.block("Cilium source verification is disabled or namespace opt-out is delegated")
    return evidence


def _deploy_workloads(lab):
    _create(lab, _pod(CLIENT))
    for name, marker in MARKERS.items():
        _create(lab, _pod(name, marker=marker))
    addresses = {name: _wait_pod(lab, name) for name in (CLIENT, DENIED_SINK, ALLOWED_SINK)}
    pods = json.loads(_kubectl(lab, "-n", NAMESPACE, "get", "pods", "-o", "json").stdout)["items"]
    case_pods = {pod["metadata"]["name"]: pod for pod in pods
                 if pod.get("metadata", {}).get("name") in addresses}
    if set(case_pods) != set(addresses):
        lab.block("The expected case-owned Pods are not present")
    annotation_clear = all(DISABLE_ANNOTATION not in pod.get("metadata", {}).get("annotations", {})
                           for pod in case_pods.values())
    if not annotation_clear:
        lab.block("A case Pod unexpectedly contains the source-verification opt-out annotation")
    return addresses, annotation_clear, {name: item["metadata"]["uid"] for name, item in case_pods.items()}


def _hubble_flows(lab, destination):
    output = _cilium_exec(
        lab, "hubble", "observe", "--server", HUBBLE_SERVER, "--since", "90s",
        "--from-pod", f"{NAMESPACE}/{CLIENT}", "--to-pod", f"{NAMESPACE}/{destination}",
        "--output", "json",
    )
    return [json.loads(line) for line in output.splitlines() if line.strip()], output


def _uuid(event):
    return event.get("flow", event).get("uuid")


def _request(lab, destination, marker=None):
    result = _kubectl(
        lab, "-n", NAMESPACE, "exec", f"pod/{CLIENT}", "--", "wget", "-q", "-T", "2",
        "-O", "-", f"http://{destination}:{PORT}/", timeout=14, allow_failure=True,
    )
    if marker is not None:
        ok = result.returncode == 0 and result.stdout.strip() == marker
        return ok, "fixed-marker-received" if ok else "fixed-marker-missing"
    return result.returncode != 0 and not result.stdout.strip(), "no-application-response"


def _observe(lab, phase, source_ip, destination_name, destination_ip, expected_verdict, marker=None):
    deadline = time.monotonic() + 30
    while True:
        before, _ = _hubble_flows(lab, destination_name)
        baseline = {_uuid(event) for event in before if _uuid(event)}
        app_ok, app_result = _request(lab, destination_ip, marker)
        after, raw = _hubble_flows(lab, destination_name)
        fresh = [event for event in after if _uuid(event) and _uuid(event) not in baseline]
        matching = []
        for event in fresh:
            flow = event.get("flow", event)
            source = flow.get("source") or {}
            destination = flow.get("destination") or {}
            ip = flow.get("IP") or flow.get("ip") or {}
            tcp = (flow.get("l4") or {}).get("TCP") or {}
            if (source.get("namespace") == NAMESPACE and source.get("pod_name") == CLIENT
                    and destination.get("namespace") == NAMESPACE
                    and destination.get("pod_name") == destination_name
                    and ip.get("source") and ip.get("destination") == destination_ip
                    and tcp.get("destination_port") == PORT
                    and flow.get("traffic_direction") == "EGRESS"):
                matching.append(flow)
        verdict_ok = any(flow.get("verdict") == expected_verdict for flow in matching)
        reason_ok = (expected_verdict != "DROPPED" or any(
            flow.get("verdict") == "DROPPED" and flow.get("drop_reason_desc") == "POLICY_DENIED"
            for flow in matching))
        source_ip_ok = bool(matching) and all(
            (flow.get("IP") or flow.get("ip") or {}).get("source") == source_ip
            for flow in matching
        )
        if app_ok and verdict_ok and reason_ok and source_ip_ok:
            break
        if time.monotonic() >= deadline:
            lab.block(f"{phase} did not produce matching application and Hubble evidence")
        time.sleep(0.5)

    raw_path = lab.evidence / "hubble-raw.jsonl"
    with raw_path.open("a") as stream:
        stream.write(f"# {phase} {destination_name}\n")
        stream.write(raw)
        if raw and not raw.endswith("\n"):
            stream.write("\n")
    receipt = {
        "phase": phase, "destination": destination_name,
        "application_result": app_result, "expected_verdict": expected_verdict,
        "observed_expected_ordinary_verdict": verdict_ok,
        "destination_ip_matches_pod_ip": any(
            (flow.get("IP") or flow.get("ip") or {}).get("destination") == destination_ip for flow in matching),
        "hubble_endpoint_identity_observed": any((flow.get("source") or {}).get("identity", 0) > 0
                                                 for flow in matching),
        "source_ip_matches_pod_ip": source_ip_ok,
        "policy_drop_reason_matches": reason_ok,
    }
    normalized_path = lab.evidence / "hubble-normalized.json"
    receipts = json.loads(normalized_path.read_text()) if normalized_path.exists() else []
    receipts.append(receipt)
    normalized_path.write_text(json.dumps(receipts, indent=2, sort_keys=True) + "\n")
    lab.check(
        phase, f"{phase} request has the expected Cilium Hubble verdict and endpoint/IP attribution",
        app_ok and verdict_ok and reason_ok and source_ip_ok,
        {"source_pod": f"{NAMESPACE}/{CLIENT}",
         "destination_pod": f"{NAMESPACE}/{destination_name}", "protocol": f"TCP/{PORT}",
         "expected_verdict": expected_verdict, "hubble_flow_matches": bool(matching),
         "source_ip_matches_pod_ip": source_ip_ok, "application_result": app_result,
         "policy_drop_reason_matches": reason_ok},
    )


def run(lab):
    version = json.loads(lab.kubectl("version", "-o", "json").stdout)
    server = version.get("serverVersion", {}).get("gitVersion", "")
    if server != KUBERNETES_VERSION:
        lab.block(f"Expected Kubernetes {KUBERNETES_VERSION}, got {server!r}")

    cluster_identity = _install_cilium(lab)
    lab.check("positive", "Digest-pinned Cilium and its source-verification configuration are active",
              True, cluster_identity)
    configuration = _policy_configuration(lab)
    (lab.evidence / "cilium-config-raw.json").write_text(
        json.dumps(configuration["cilium_configmap"], indent=2) + "\n")
    normalized_config = {
        "cilium_release": CILIUM_VERSION,
        "enable-source-ip-verification": configuration["source_ip_verification_enabled"],
        "namespace_opt_out_delegated": not configuration["namespace_does_not_delegate_opt_out"],
    }
    (lab.evidence / "cilium-config-normalized.json").write_text(
        json.dumps(normalized_config, indent=2, sort_keys=True) + "\n")

    addresses, annotation_clear, pod_uids = _deploy_workloads(lab)
    source_ip = addresses[CLIENT]
    (lab.evidence / "cilium-runtime-pods.json").write_text(json.dumps({
        "pod_uids": pod_uids, "addresses": addresses, "agent": cluster_identity,
    }, indent=2, sort_keys=True) + "\n")
    config_ok = configuration["source_ip_verification_enabled"] and annotation_clear
    lab.check("positive", "Case workloads inherit enabled source verification without opt-out annotations",
              config_ok,
              {"global_source_ip_verification_enabled": configuration["source_ip_verification_enabled"],
               "namespace_delegates_opt_out": not configuration["namespace_does_not_delegate_opt_out"],
               "pod_opt_out_annotations_absent": annotation_clear})

    # Red phase is a reachable, unisolated baseline and validates CNI telemetry attribution.
    _observe(lab, "red", source_ip, DENIED_SINK, addresses[DENIED_SINK], "FORWARDED",
             MARKERS[DENIED_SINK])

    _create(lab, _policy())
    _capture_policy(lab)
    # Green phase denies only the ordinary request to the unselected sink.
    _observe(lab, "green", source_ip, DENIED_SINK, addresses[DENIED_SINK], "DROPPED")

    # Positive phase proves the named endpoint remains reachable through the CNI policy.
    _observe(lab, "positive", source_ip, ALLOWED_SINK, addresses[ALLOWED_SINK], "FORWARDED",
             MARKERS[ALLOWED_SINK])

    # Keep cleanup explicitly scoped to names and objects created by this case.
    _kubectl(lab, "-n", NAMESPACE, "delete", "networkpolicy", "saf-0502-007-client-egress",
             "--ignore-not-found=true", allow_failure=True)
    _kubectl(lab, "-n", NAMESPACE, "delete", "pod", CLIENT, DENIED_SINK, ALLOWED_SINK,
             "--wait=true", "--timeout=35s", timeout=45, allow_failure=True)
